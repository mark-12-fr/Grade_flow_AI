/**
 * Shared helpers for filming the real app (scripts/capture-*.mjs): start the built app with no AI key,
 * save WebP captures, read element boxes, slow the page's own CSS animations down to film them, and
 * render downloaded PDFs to images.
 */
import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export function requireTools(root) {
  for (const [tool, args] of [['ffmpeg', ['-version']], ['pdftoppm', ['-v']]]) {
    if (spawnSync(tool, args).error) throw new Error(`${tool} is required (ffmpeg for WebP, pdftoppm from poppler-utils for the PDFs).`);
  }
  if (!existsSync(path.join(root, '.next', 'BUILD_ID'))) throw new Error('Build the app first: npm run build');
}

/** Starts `next start` on a free port with no AI key, so imports use the built-in template reader. */
export async function startApp(root, port) {
  const server = spawn(process.execPath, [path.join(root, 'node_modules', 'next', 'dist', 'bin', 'next'), 'start', '-p', String(port)], {
    cwd: root, env: { ...process.env, AI_API_KEY: '', AI_REQUIRED: '', APP_ACCESS_CODE: '' }, stdio: ['ignore', 'ignore', 'inherit']
  });
  const base = `http://localhost:${port}`;
  for (let i = 0; ; i++) {
    try { if ((await fetch(`${base}/api/health`)).ok) break; } catch { /* not up yet */ }
    if (i > 60) { server.kill(); throw new Error('The app did not start on port ' + port); }
    await new Promise((r) => setTimeout(r, 500));
  }
  return { base, stop: () => server.kill() };
}

/** A captures folder: WebP files plus a manifest that a reel loads as window[varName]. Everything is written
    to `<outDir>.new` first; write() swaps it in, so a capture that fails half way keeps the old captures. */
export function shotsFolder(outDir, varName, manifest) {
  const staging = `${outDir}.new`;
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  manifest.shots ??= {};
  function save(name, png, meta) {
    const file = `${name}.webp`;
    const res = spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'png_pipe', '-i', '-', '-c:v', 'libwebp', '-quality', '88', '-compression_level', '6', path.join(staging, file)], { input: png });
    if (res.status !== 0) throw new Error(`WebP encode failed for ${name}: ${res.stderr}`);
    manifest.shots[name] = { file, ...meta };
  }
  function pdf(pdfPath, prefix, dpi = 220) { // every page of a PDF, as `${prefix}-1`, `${prefix}-2`...
    const dir = path.dirname(pdfPath), stem = path.join(dir, `${prefix}-page`);
    const res = spawnSync('pdftoppm', ['-r', String(dpi), '-png', pdfPath, stem]);
    if (res.status !== 0) throw new Error(`pdftoppm failed for ${pdfPath}: ${res.stderr}`);
    return readdirSync(dir).filter((f) => f.startsWith(`${prefix}-page`) && f.endsWith('.png')).sort().map((f, i) => {
      const png = readFileSync(path.join(dir, f));
      save(`${prefix}-${i + 1}`, png, { w: png.readUInt32BE(16), h: png.readUInt32BE(20) }); // PNG IHDR width/height
      return `${prefix}-${i + 1}`;
    });
  }
  function write(note) {
    writeFileSync(path.join(staging, 'manifest.js'),
      `/* Generated by ${note} from the real app. Do not edit by hand. */\nwindow.${varName} = ${JSON.stringify(manifest, null, 1)};\n`);
    rmSync(outDir, { recursive: true, force: true });
    renameSync(staging, outDir);
    return readdirSync(outDir).length - 1;
  }
  const discard = () => rmSync(staging, { recursive: true, force: true }); // after a failed capture
  return { save, pdf, write, discard };
}

/** Page helpers. Boxes are in page coordinates (CSS px), so they stay valid in full-page captures. */
export function pageKit(page, save, view) {
  const wait = (ms) => page.waitForTimeout(ms);
  async function box(locator) {
    const b = await locator.first().boundingBox();
    if (!b) throw new Error(`No box for ${locator}`);
    const sy = await page.evaluate(() => window.scrollY);
    return { x: Math.round(b.x), y: Math.round(b.y + sy), w: Math.round(b.width), h: Math.round(b.height) };
  }
  async function shot(name, opts = {}) {
    const png = await page.screenshot({ type: 'png', ...opts });
    const size = opts.clip ? { w: opts.clip.width, h: opts.clip.height } : opts.fullPage
      ? await page.evaluate(() => ({ w: document.documentElement.scrollWidth, h: document.documentElement.scrollHeight })) : { w: view.width, h: view.height };
    save(name, png, { ...size, ...(opts.clip ? { x: opts.clip.x, y: opts.clip.y } : {}) });
  }
  async function dismissToast() {
    const close = page.locator('.toast.show .toast-close');
    if (await close.count()) { await close.click(); await wait(500); }
  }
  async function settle(ms = 700) { await page.evaluate(() => document.fonts.ready); await wait(ms); }
  const scrollTo = (y) => page.evaluate((y) => window.scrollTo({ top: y, behavior: 'instant' }), y);
  const scrollY = () => page.evaluate(() => Math.round(window.scrollY));
  /** Waits until a smooth scroll has stopped, then returns where it stopped. */
  async function scrollSettled() {
    let last = -1, same = 0;
    for (let i = 0; i < 100 && same < 4; i++) { await wait(80); const y = await scrollY(); same = y === last ? same + 1 : 0; last = y; }
    return last;
  }
  return { wait, box, shot, dismissToast, settle, scrollTo, scrollY, scrollSettled };
}
