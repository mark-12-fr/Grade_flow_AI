"""AI column mapping + deterministic value copying.

Claude only decides WHICH column is WHICH field. Every learner value is then copied
from the spreadsheet by code, so no grade is ever generated by the model.
"""
from __future__ import annotations

import json
import os
import re
from typing import Any, Callable

from .extractor import Grid, preview_text

DEFAULT_MODEL = "claude-sonnet-5-5"
LEARNER_FIELDS = ["roll", "name", "middleName", "age", "sex", "lrn", "birthdate"]
CLASS_FIELDS = ["className", "strand", "gradeLevel", "year", "term", "section",
                "studentStatus", "graduationStatus", "teacher", "principal",
                "schoolName", "department", "region", "division", "schoolAddress", "track"]
PERIODS = ["q1", "q2", "q3", "q4", "final"]
ATT_FIELDS = ["schoolDays", "present", "absent"]
OV_PERIODS = ["q1", "q2", "q3", "q4"]
FOOTER_WORDS = re.compile(
    r"^((class|general|overall|section|grand)\s+)?(total|average|ave\.?|mean|passed|failed|remarks?|"
    r"prepared by|checked by|noted by|certified correct)\b", re.I)


class MappingError(RuntimeError):
    """kind: 'config' (server not set up), 'file' (layout not understood), 'ai' (service failure)."""

    def __init__(self, message: str, kind: str = "ai"):
        super().__init__(message)
        self.kind = kind


def allowed_fields(schema: dict) -> set[str]:
    fields = set(LEARNER_FIELDS)
    for s in schema["subjects"]:
        fields.update(f"grade:{s['key']}:{p}" for p in PERIODS)
    for m in schema["months"]:
        fields.update(f"att:{m}:{f}" for f in ATT_FIELDS)
    for v in schema["coreValues"]:
        fields.update(f"ov:{v}:{p}" for p in OV_PERIODS)
    fields.update(f"transfer:{t}" for t in schema["transferFields"])
    return fields


def build_tool(schema: dict) -> dict:
    return {
        "name": "submit_column_mapping",
        "description": "Report where each learner field lives in the spreadsheet. Never invent values.",
        "input_schema": {
            "type": "object",
            "properties": {
                "header_row": {"type": "integer", "description": "Row index of the (last) header row"},
                "first_data_row": {"type": "integer", "description": "Row index of the first learner row"},
                "columns": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {"col": {"type": "integer"}, "field": {"type": "string"}},
                        "required": ["col", "field"],
                    },
                },
                "class_details": {
                    "type": "object",
                    "description": "Class-level values read from title rows or a constant column. Allowed keys: " + ", ".join(CLASS_FIELDS),
                    "additionalProperties": {"type": "string"},
                },
                "warnings": {"type": "array", "items": {"type": "string"}},
            },
            "required": ["header_row", "first_data_row", "columns"],
        },
    }


def build_prompt(schema: dict, grid: Grid) -> str:
    subjects = "\n".join(f"- {s['key']}  =  {s['name']}  (semester: {s['semester']})" for s in schema["subjects"])
    return f"""You map a Philippine Senior High School class gradebook spreadsheet onto a fixed schema.

You see only the top rows of the sheet. Row and column indexes are 0-based and shown in the table header.
Call submit_column_mapping exactly once.

Field names you may use in `columns[].field`:
- Learner: {', '.join(LEARNER_FIELDS)}  (name = full learner name; birthdate = date of birth)
- Grades: grade:<subjectKey>:<period>   period is one of q1,q2,q3,q4,final.
  `final` is that subject's semester final grade. Subjects 1st semester use q1,q2; 2nd semester use q3,q4.
- Attendance: att:<month>:<schoolDays|present|absent>   months: {', '.join(schema['months'])}
- Core values: ov:<value>:<q1..q4>   values: {', '.join(schema['coreValues'])}
- Transfer: transfer:<field>   fields: {', '.join(schema['transferFields'])}

Subject keys:
{subjects}

Rules:
- Map a column only if you are confident. Skip unrelated columns (totals, remarks, signatures).
- Headers may be spread over several rows (subject on one row, Q1/Q2 beneath) and may use abbreviations, Filipino names or different order.
- Put class-level facts found in title rows (school year, strand, grade level, section, adviser, principal) into `class_details`.
- If a subject, period or learner column cannot be found, do not guess; add a short entry to `warnings`.
- Never output grade values. You only describe the layout.

Sheet "{grid.sheet}" (top rows):
{preview_text(grid)}
"""


def call_claude(prompt: str, tool: dict, client: Any | None = None, max_tokens: int = 4096) -> dict:
    if client is None:
        if not os.environ.get("ANTHROPIC_API_KEY"):
            raise MappingError("ANTHROPIC_API_KEY is not configured on the server.", "config")
        try:
            import anthropic
        except ImportError as exc:
            raise MappingError("The 'anthropic' package is not installed on the server (pip install -r requirements.txt).", "config") from exc
        client = anthropic.Anthropic()
    try:
        msg = client.messages.create(
            model=os.environ.get("ANTHROPIC_MODEL", DEFAULT_MODEL),
            max_tokens=max_tokens,
            tools=[tool],
            tool_choice={"type": "tool", "name": tool["name"]},
            messages=[{"role": "user", "content": prompt}],
        )
    except Exception as exc:
        raise MappingError(f"The AI service request failed: {exc}") from exc
    for block in msg.content:
        if getattr(block, "type", "") == "tool_use":
            return dict(block.input)
    raise MappingError("The AI service returned no mapping.")


def _num(value: object) -> tuple[float | int | None, bool]:
    """(number, ok). Empty -> (None, True). Unparseable -> (None, False)."""
    if value is None or str(value).strip() in ("", "-", "—", "n/a", "N/A"):
        return None, True
    try:
        n = float(str(value).strip().rstrip("%"))
    except ValueError:
        return None, False
    return (int(n) if n.is_integer() else n), True


def _int(value: object) -> tuple[int | None, bool]:
    n, ok = _num(value)
    if not ok:
        return None, False
    if n is None:
        return None, True
    return (int(n), True) if float(n).is_integer() and n >= 0 else (None, False)


def _lrn(value: object) -> str:
    text = str(value).strip()
    if re.fullmatch(r"\d+\.0+", text):
        text = text.split(".")[0]
    if re.fullmatch(r"\d(\.\d+)?[eE]\+?\d+", text):
        text = str(int(float(text)))
    return text


def _sex(value: object) -> str:
    t = str(value).strip().lower()
    if t in ("m", "male", "lalaki", "boy"):
        return "Male"
    if t in ("f", "female", "babae", "girl"):
        return "Female"
    return str(value).strip()


def validate_mapping(raw: dict, schema: dict, width: int, nrows: int) -> tuple[dict, list[str]]:
    allowed = allowed_fields(schema)
    warnings = [str(w) for w in raw.get("warnings", []) if str(w).strip()]
    cols: dict[int, str] = {}
    used: set[str] = set()
    for item in raw.get("columns", []):
        try:
            col, name = int(item["col"]), str(item["field"])
        except (KeyError, TypeError, ValueError):
            continue
        if not (0 <= col < width) or name not in allowed:
            warnings.append(f"Ignored an unusable mapping ({name!r} -> column {col}).")
            continue
        if name in used:
            warnings.append(f"Field {name!r} was mapped to more than one column; kept the first.")
            continue
        cols[col] = name
        used.add(name)
    if "name" not in used:
        raise MappingError("Could not find the learner name column in this file.", "file")
    first = raw.get("first_data_row")
    if not isinstance(first, int) or not (0 <= first < nrows):
        raise MappingError("Could not tell where the learner rows start.", "file")
    details = {k: str(v).strip() for k, v in (raw.get("class_details") or {}).items() if k in CLASS_FIELDS and str(v).strip()}
    return {"columns": cols, "first": first, "details": details}, warnings


def apply_mapping(grid: Grid, mapping: dict, schema: dict) -> tuple[list[dict], list[str]]:
    cols: dict[int, str] = mapping["columns"]
    name_col = next(c for c, f in cols.items() if f == "name")
    warnings: list[str] = []
    students: list[dict] = []
    seen_rolls: set[str] = set()
    for r in range(mapping["first"], len(grid.rows)):
        row = grid.rows[r]
        name = str(row[name_col]).strip() if name_col < len(row) else ""
        if not name:
            continue
        if FOOTER_WORDS.match(name):
            break
        stu: dict[str, Any] = {
            "id": len(students) + 1, "roll": "", "name": name[:80], "middleName": "", "age": "", "sex": "", "lrn": "", "birthdate": "",
            "grades": {s["key"]: {} for s in schema["subjects"]},
            "attendance": {"present": None, "total": None, "months": {}, "schoolDays": {}, "absent": {}},
            "transfer": {}, "observedValues": {v: {} for v in schema["coreValues"]},
            "comment": "", "commentReviewed": True, "traits": None, "nextSteps": None,
        }
        for c, f in cols.items():
            cell = row[c] if c < len(row) else ""
            parts = f.split(":")
            if f in LEARNER_FIELDS:
                if f == "name":
                    continue
                stu[f] = _lrn(cell) if f == "lrn" else _sex(cell) if f == "sex" else str(cell).strip()
            elif parts[0] == "grade":
                n, ok = _num(cell)
                if not ok:
                    warnings.append(f"{name}: '{str(cell)[:20]}' in {f} is not a number; left blank.")
                stu["grades"][parts[1]][parts[2]] = n
            elif parts[0] == "att":
                n, ok = _int(cell)
                if not ok:
                    warnings.append(f"{name}: '{str(cell)[:20]}' in {f} is not a whole number; left blank.")
                bucket = {"schoolDays": "schoolDays", "present": "months", "absent": "absent"}[parts[2]]
                stu["attendance"][bucket][parts[1]] = n
            elif parts[0] == "ov":
                stu["observedValues"][parts[1]][parts[2]] = str(cell).strip().upper()
            elif parts[0] == "transfer":
                stu["transfer"][parts[1]] = str(cell).strip()
        # make sure every expected key exists so the UI never sees undefined
        for s in schema["subjects"]:
            for p in [*(["q1", "q2"] if s["semester"] == "first" else ["q3", "q4"]), "final"]:
                stu["grades"][s["key"]].setdefault(p, None)
        days = [v for v in stu["attendance"]["schoolDays"].values() if isinstance(v, int)]
        pres = [v for v in stu["attendance"]["months"].values() if isinstance(v, int)]
        if days:
            stu["attendance"]["total"], stu["attendance"]["present"] = sum(days), sum(pres)
        roll = stu["roll"] or str(len(students) + 1).zfill(2)
        while roll.lower() in seen_rolls:
            roll += "*"
            warnings.append(f"{name}: duplicate roll number; adjusted to {roll}.")
        seen_rolls.add(roll.lower())
        stu["roll"] = roll
        students.append(stu)
    if not students:
        raise MappingError("No learner rows were found below the header.", "file")
    return students, warnings


def header_labels(grid: Grid, first_data_row: int, columns: dict[int, str]) -> dict[int, str]:
    """Human label per mapped column: the up-to-2 header rows above the data, joined.

    Spreadsheet headers are often two rows (subject over Q1/Q2) with the top cell merged, so an
    empty top cell borrows from the nearest non-empty cell up to 2 columns to its left.
    Title rows are ignored so they cannot leak into neighbouring columns.
    """
    # A header row has text above several mapped columns; a title row ("School, SY 2026") has
    # text in only one place, so it must not lend its words to the columns beside it.
    need = min(2, len(columns))
    rows = [r for r in range(max(0, first_data_row - 2), first_data_row)
            if sum(1 for c in columns if c < len(grid.rows[r]) and str(grid.rows[r][c]).strip()) >= need]
    out: dict[int, str] = {}
    for c in columns:
        parts: list[str] = []
        for r in rows:
            row = grid.rows[r]
            cell = ""
            for k in range(c, max(-1, c - 3), -1):
                if k < len(row) and str(row[k]).strip():
                    cell = str(row[k]).strip()
                    break
            if cell and cell not in parts:
                parts.append(cell)
        out[c] = " · ".join(parts)
    return out


def run_import(grid: Grid, schema: dict, client: Any | None = None,
               caller: Callable[..., dict] = call_claude) -> dict:
    tool = build_tool(schema)
    raw = caller(build_prompt(schema, grid), tool, client)
    mapping, warnings = validate_mapping(raw, schema, len(grid.rows[0]), len(grid.rows))
    students, apply_warnings = apply_mapping(grid, mapping, schema)
    labels = header_labels(grid, mapping["first"], mapping["columns"])
    if grid.skipped_sheets:
        warnings.append("Other sheets were not read: " + ", ".join(grid.skipped_sheets) + ".")
    return {
        "students": students,
        "classDetails": mapping["details"],
        "mapping": [{"col": c, "header": labels.get(c, ""), "field": f} for c, f in sorted(mapping["columns"].items())],
        "warnings": warnings + apply_warnings[:50],
        "sheet": grid.sheet,
    }


def parse_schema(text: str) -> dict:
    try:
        schema = json.loads(text)
        assert all(k in schema for k in ("subjects", "months", "coreValues", "transferFields"))
        assert all({"key", "name", "semester"} <= set(s) for s in schema["subjects"])
        return schema
    except Exception as exc:
        raise MappingError("The import schema is missing or invalid.", "file") from exc
